#!/usr/bin/env bash
#ddev-generated
# Prepares the agents service in a git worktree that fourkitchens/ddev-fire-worktrees
# gave its own DDEV project. Runs as a pre-start hook (config.agents.yaml), which
# DDEV processes before it renders the Compose files, so the overlay written here
# applies to the start that is under way. In the main checkout, or in a project
# without ddev-fire-worktrees, it only removes a stale overlay and exits.
#
# In a worktree it:
#   1. writes .ddev/docker-compose.agents-worktree.yaml, which marks the agents
#      container as a worktree (DDEV_AGENTS_WORKTREE, DDEV_AGENTS_PRIMARY_PROJECT)
#      and, when ddev-fire-worktrees mounts the shared Git directory into the web
#      container, mounts it read-only into the agents container the same way, so
#      `git status`/`git diff`/`git log` work there;
#   2. seeds Claude Code's login from the main checkout's project, so each new
#      worktree doesn't need its own `ddev claude login`
#      (opt out with DDEV_AGENTS_WORKTREE_SHARE_AUTH=false on the host);
#   3. records which checkout the state directory belongs to, for
#      `ddev agents-worktree-prune`.
# Keep it Bash 3.2 compatible (the macOS default).

set -eu

PROJECT_ROOT="$(cd "$(dirname "$0")/../.." && pwd -P)"
DDEV_DIR="$PROJECT_ROOT/.ddev"
: "${DDEV_PROJECT:?DDEV_PROJECT is not set; run this through ddev start}"

FW_CONFIG="$DDEV_DIR/config.worktree.local.yaml"
FW_MARKER='# Generated by ddev fire-worktree-start.'
FW_GIT_COMPOSE="$DDEV_DIR/docker-compose.fire-worktree-git.yaml"
FW_GIT_FILE="$DDEV_DIR/fire-worktree-git"
# Where ddev-fire-worktrees mounts the shared Git directory, and so where its
# generated .git file points.
FW_CONTAINER_GIT_DIR=/mnt/fire-worktrees/git

OVERLAY_NAME=docker-compose.agents-worktree.yaml
OVERLAY="$DDEV_DIR/$OVERLAY_NAME"
OVERLAY_MARKER='# Generated by the ddev-agents pre-start hook for a worktree. Do not edit.'
STATE_ROOT="$HOME/.ddev-agents/projects"

warn() {
    printf '⚠️  %s\n' "$*" >&2
}

# remove_overlay: delete the overlay, but only one this script wrote.
remove_overlay() {
    if [ -f "$OVERLAY" ] && [ "$(head -n 1 "$OVERLAY")" = "$OVERLAY_MARKER" ]; then
        rm -f "$OVERLAY"
    fi
}

# is_fire_worktree: true in a linked git worktree that fire-worktree-start set up.
is_fire_worktree() {
    local git_dir common_dir
    [ -f "$FW_CONFIG" ] || return 1
    case "$(head -n 1 "$FW_CONFIG")" in
        "$FW_MARKER"*) ;;
        *) return 1 ;;
    esac
    git_dir=$(cd "$PROJECT_ROOT" && cd "$(git rev-parse --git-dir 2>/dev/null)" 2>/dev/null && pwd -P) || return 1
    common_dir=$(cd "$PROJECT_ROOT" && cd "$(git rev-parse --git-common-dir 2>/dev/null)" 2>/dev/null && pwd -P) || return 1
    [ "$git_dir" != "$common_dir" ]
}

# yaml_path PATH: PATH as a double-quoted YAML string that Compose doesn't interpolate.
yaml_path() {
    local s=$1 bs=\\ q=\"
    s=${s//"$bs"/"$bs$bs"}
    s=${s//"$q"/"$bs$q"}
    s=${s//\$/\$\$}
    printf '"%s"' "$s"
}

# slug TEXT: lowercase letters, digits and single hyphens, as DDEV names a
# project after its directory.
slug() {
    local s
    s=$(printf '%s' "$1" | LC_ALL=C tr '[:upper:]' '[:lower:]' | LC_ALL=C sed -e 's/[^a-z0-9]/-/g' -e 's/--*/-/g' -e 's/^-//')
    printf '%s' "${s%-}"
}

# project_name_of DIR: the DDEV project name DIR's config gives it. The last
# config file that sets name: wins, as in DDEV; without one, DDEV uses the
# directory name.
project_name_of() {
    local f v name=
    for f in "$1/.ddev/config.yaml" "$1"/.ddev/config.*.yaml; do
        [ -f "$f" ] || continue
        [ "$f" = "$1/.ddev/config.worktree.local.yaml" ] && continue
        v=$(sed -n -E 's/^name:[[:space:]]*["'\'']?([^"'\''#[:space:]]*).*/\1/p' "$f" | tail -n 1)
        [ -n "$v" ] && name=$v
    done
    [ -n "$name" ] || name=$(slug "$(basename "$1")")
    printf '%s' "$name"
}

# exclude_from_git PATH: ignore PATH in every checkout through the shared
# info/exclude, so a generated file never shows up as untracked (which would
# also make `ddev fire-worktree-remove` refuse to delete the checkout).
exclude_from_git() {
    local exclude
    exclude="$COMMON_DIR/info/exclude"
    mkdir -p "$(dirname "$exclude")"
    grep -qxF "$1" "$exclude" 2>/dev/null || printf '%s\n' "$1" >>"$exclude"
}

write_overlay() {
    local tmp="$OVERLAY.tmp"
    {
        printf '%s\n' "$OVERLAY_MARKER"
        printf '%s\n' '#ddev-silent-no-warn'
        cat <<YAML
services:
  agents:
    environment:
      - DDEV_AGENTS_WORKTREE=true
      - DDEV_AGENTS_PRIMARY_PROJECT=$PRIMARY_NAME
YAML
        # Mirror ddev-fire-worktrees' web-container Git mount: the shared Git
        # directory read-only at the path its .git file points to, and that file
        # read-only over the worktree's own .git (which holds a host path the
        # container can't resolve). Read-only because the container can't see
        # the other worktrees, so a `git worktree prune` there would delete their
        # metadata. Skipped when that add-on doesn't mount Git
        # (WORKTREE_MOUNT_GIT=false, or DDEV's no_bind_mounts).
        if [ -f "$FW_GIT_COMPOSE" ] && [ -f "$FW_GIT_FILE" ]; then
            cat <<YAML
    volumes:
      - type: bind
        source: $(yaml_path "$COMMON_DIR")
        target: $FW_CONTAINER_GIT_DIR
        read_only: true
        bind:
          create_host_path: false
      - type: bind
        source: "\${DDEV_APPROOT}/.ddev/$(basename "$FW_GIT_FILE")"
        target: /workspace/.git
        read_only: true
        bind:
          create_host_path: false
YAML
        fi
    } >"$tmp"
    mv "$tmp" "$OVERLAY"
}

# seed_claude_auth: copy the main checkout's Claude Code login into this
# worktree's state directory when it has none yet. Chat history stays
# per-worktree: the .projects map in claude.json is not copied.
seed_claude_auth() {
    local src="$STATE_ROOT/$PRIMARY_NAME/claude" dst="$STATE_ROOT/$DDEV_PROJECT/claude"
    case "${DDEV_AGENTS_WORKTREE_SHARE_AUTH:-true}" in
        false | 0 | no) return 0 ;;
    esac
    [ "$src" != "$dst" ] || return 0
    [ -f "$src/claude/.credentials.json" ] || return 0
    [ -f "$dst/claude/.credentials.json" ] && return 0

    mkdir -p "$dst/claude"
    chmod 700 "$dst" "$dst/claude"
    (umask 077 && cp "$src/claude/.credentials.json" "$dst/claude/.credentials.json")

    # claude.json carries the account and onboarding state Claude Code checks
    # before it trusts the credentials. Only replace an empty one.
    if [ -f "$src/claude.json" ] && { [ ! -s "$dst/claude.json" ] || [ "$(tr -d '[:space:]' <"$dst/claude.json")" = '{}' ]; }; then
        if command -v jq >/dev/null 2>&1; then
            (umask 077 && jq 'del(.projects)' "$src/claude.json" >"$dst/claude.json.tmp" && mv "$dst/claude.json.tmp" "$dst/claude.json")
        else
            warn "jq not found; copied the Claude login but not claude.json. Claude Code may ask you to log in."
        fi
    fi
    echo "🔑 Claude Code login copied from project '$PRIMARY_NAME'."
}

# record_state_owner: note which checkout this state directory belongs to, so
# `ddev agents-worktree-prune` can find state left by removed worktrees.
record_state_owner() {
    local dir="$STATE_ROOT/$DDEV_PROJECT"
    mkdir -p "$dir"
    printf 'primary=%s\npath=%s\n' "$PRIMARY_NAME" "$PROJECT_ROOT" >"$dir/worktree"
}

if ! is_fire_worktree; then
    remove_overlay
    exit 0
fi

COMMON_DIR=$(cd "$PROJECT_ROOT" && cd "$(git rev-parse --git-common-dir)" && pwd -P)
PRIMARY_ROOT=$(dirname "$COMMON_DIR")
PRIMARY_NAME=$(project_name_of "$PRIMARY_ROOT")

echo "🌳 Worktree of '$PRIMARY_NAME': preparing the agents container for project '$DDEV_PROJECT'."
exclude_from_git ".ddev/$OVERLAY_NAME"
write_overlay
seed_claude_auth || warn "Could not copy the Claude Code login; run 'ddev claude login' in this worktree."
record_state_owner
